#!/usr/bin/env python3
# make shaders: compiled SPIR-V -> src/upscale_spv.h (committed, so building
# tonic does not need a shader compiler).
import sys
out = ['// Generated by tools/spv2h.py from shaders/*.comp (make shaders). Do not edit.', '#pragma once', '#include <cstdint>', '']
for path in sys.argv[2:]:
    name = path.rsplit('/', 1)[-1].split('.')[0]
    data = open(path, 'rb').read()
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    out.append('static const uint32_t kSpv_%s[] = {' % name)
    for i in range(0, len(words), 8):
        out.append('  ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    out.append('};')
    out.append('')
open(sys.argv[1], 'w').write('\n'.join(out))
